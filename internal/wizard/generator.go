package wizard

import (
	"fmt"
	"os"

	"github.com/xenos76/errant/internal/config"
	"gopkg.in/yaml.v3"
)

// GenerateConfig builds a config.Config instance from collected user answers.
func GenerateConfig(ans Answers) *config.Config {
	images := DefaultOSImages()

	imageURL := ans.CustomImage
	imageAlias := "custom"
	sshUser := ans.DefaultUser

	if ans.ImageIndex >= 0 && ans.ImageIndex < len(images) && ans.CustomImage == "" {
		img := images[ans.ImageIndex]
		imageURL = img.URL
		imageAlias = img.Alias
		sshUser = img.DefaultUser
	}

	dhcp := true
	cfg := &config.Config{
		Version: "1",
		Project: ans.ProjectName,
		Defaults: config.DefaultsConfig{
			Image:        imageURL,
			ImageAlias:   imageAlias,
			Driver:       "libvirt",
			MemoryMB:     ans.MemoryMB,
			CPUs:         ans.CPUs,
			RootDiskSize: ans.RootDiskSize,
			SSH: config.SSHConfig{
				User: sshUser,
			},
		},
		Network: config.NetworkConfig{
			Mode:   "private",
			Subnet: ans.Subnet,
			Bridge: ans.Bridge,
			DHCP:   &dhcp,
		},
		Profiles:   make(map[string]config.ProfileConfig),
		Topologies: make(map[string]config.TopologyConfig),
	}

	if ans.SyncFolder {
		cfg.Defaults.SyncedFolders = []config.SyncedFolderConfig{
			{
				Source: ".",
				Target: "/errant",
				Type:   "virtiofs",
			},
		}
	}

	switch ans.ArchetypeID {
	case "single-vm":
		populateSingleVM(cfg)
	case "k8s-ha":
		populateK8sHA(cfg)
	case "custom":
		populateCustom(cfg, ans)
	default: // "k8s-cluster"
		populateK8sStandard(cfg)
	}

	return cfg
}

func populateSingleVM(cfg *config.Config) {
	cfg.Topologies["dev"] = config.TopologyConfig{
		Description: "Single standalone development VM",
		Nodes: []config.NodeConfig{
			{
				Name: "dev-vm",
				IP:   "192.168.56.10",
			},
		},
	}
}

func populateK8sStandard(cfg *config.Config) {
	cfg.Profiles["control-plane"] = config.ProfileConfig{
		Role:     "control-plane",
		MemoryMB: 4096,
		CPUs:     2,
		Disks: []config.DiskConfig{
			{
				Device: "vdb",
				Size:   "20G",
				Format: "qcow2",
			},
		},
	}

	cfg.Profiles["worker"] = config.ProfileConfig{
		Role:     "worker",
		MemoryMB: 2048,
		CPUs:     2,
	}

	cfg.Topologies["standard"] = config.TopologyConfig{
		Description: "Standard Kubernetes: 1 Control Plane + 2 Workers",
		Nodes: []config.NodeConfig{
			{
				Name:    "kube-control-plane",
				Profile: "control-plane",
				IP:      "192.168.56.10",
			},
			{
				Name:    "kube-worker-${index}",
				Profile: "worker",
				Count:   2,
				IPStart: "192.168.56.21",
			},
		},
	}
}

func populateK8sHA(cfg *config.Config) {
	cfg.Profiles["control-plane"] = config.ProfileConfig{
		Role:     "control-plane",
		MemoryMB: 3072,
		CPUs:     2,
		Disks: []config.DiskConfig{
			{
				Condition: "${index} == 1",
				Device:    "vdb",
				Size:      "20G",
				Format:    "qcow2",
			},
		},
	}

	cfg.Profiles["worker"] = config.ProfileConfig{
		Role:     "worker",
		MemoryMB: 2048,
		CPUs:     2,
	}

	cfg.Topologies["ha"] = config.TopologyConfig{
		Description: "High Availability Kubernetes: 3 Control Planes + 2 Workers",
		Nodes: []config.NodeConfig{
			{
				Name:    "kube-cp-${index}",
				Profile: "control-plane",
				Count:   3,
				IPStart: "192.168.56.10",
			},
			{
				Name:    "kube-worker-${index}",
				Profile: "worker",
				Count:   2,
				IPStart: "192.168.56.21",
			},
		},
	}
}

func populateCustom(cfg *config.Config, ans Answers) {
	cfg.Profiles["control-plane"] = config.ProfileConfig{
		Role:     "control-plane",
		MemoryMB: ans.MemoryMB,
		CPUs:     ans.CPUs,
	}

	cfg.Profiles["worker"] = config.ProfileConfig{
		Role:     "worker",
		MemoryMB: ans.MemoryMB,
		CPUs:     ans.CPUs,
	}

	var nodes []config.NodeConfig

	if ans.ControlNodes > 0 {
		nodes = append(nodes, config.NodeConfig{
			Name:    "cp-${index}",
			Profile: "control-plane",
			Count:   ans.ControlNodes,
			IPStart: "192.168.56.10",
		})
	}

	if ans.WorkerNodes > 0 {
		nodes = append(nodes, config.NodeConfig{
			Name:    "worker-${index}",
			Profile: "worker",
			Count:   ans.WorkerNodes,
			IPStart: "192.168.56.21",
		})
	}

	cfg.Topologies["custom"] = config.TopologyConfig{
		Description: "Custom topology generated by Errant wizard",
		Nodes:       nodes,
	}
}

// RenderYAML generates a formatted YAML string with schema header and comments.
func RenderYAML(ans Answers) ([]byte, error) {
	cfg := GenerateConfig(ans)

	rawBytes, err := yaml.Marshal(cfg)
	if err != nil {
		return nil, fmt.Errorf("marshalling config to YAML: %w", err)
	}

	header := "# yaml-language-server: $schema=./schema/errantfile.schema.json\n"
	fullYAML := append([]byte(header), rawBytes...)

	if err := config.ValidateYAML(fullYAML); err != nil {
		return nil, fmt.Errorf("generated configuration failed schema validation: %w", err)
	}

	return fullYAML, nil
}

// WriteErrantfile generates and writes the Errantfile to the designated output path.
func WriteErrantfile(ans Answers) (string, error) {
	target := ans.OutputPath
	if target == "" {
		target = "Errantfile.yaml"
	}

	yamlContent, err := RenderYAML(ans)
	if err != nil {
		return "", err
	}

	if err := os.WriteFile(target, yamlContent, 0o600); err != nil {
		return "", fmt.Errorf("writing configuration file %s: %w", target, err)
	}

	return target, nil
}
