package generator

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/xenos76/errant/internal/config"
)

// GenerateSSHConfig writes an OpenSSH client configuration file for all nodes.
func GenerateSSHConfig(cluster *config.ResolvedCluster, destFile string) error {
	if err := os.MkdirAll(filepath.Dir(destFile), 0o755); err != nil {
		return err
	}

	var sb strings.Builder

	_, _ = sb.WriteString("# Generated by Errant - DO NOT EDIT MANUALLY\n\n")

	for _, node := range cluster.Nodes {
		fmt.Fprintf(&sb, "Host %s\n", node.Name)

		if node.IP != "" {
			fmt.Fprintf(&sb, "  HostName %s\n", node.IP)
		}

		user := node.SSH.User
		if user == "" {
			user = "errant"
		}

		fmt.Fprintf(&sb, "  User %s\n", user)

		port := node.SSH.Port
		if port <= 0 {
			port = 22
		}

		fmt.Fprintf(&sb, "  Port %d\n", port)

		if node.SSH.PrivateKey != "" {
			fmt.Fprintf(&sb, "  IdentityFile %s\n", node.SSH.PrivateKey)
		}

		_, _ = sb.WriteString("  StrictHostKeyChecking no\n")
		_, _ = sb.WriteString("  UserKnownHostsFile /dev/null\n")
		_, _ = sb.WriteString("  LogLevel ERROR\n\n")
	}

	return os.WriteFile(destFile, []byte(sb.String()), 0o600)
}
