package generator

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/xenos76/errant/internal/config"
)

// GenerateAnsibleInventory writes an Ansible hosts.ini inventory grouped by role.
func GenerateAnsibleInventory(cluster *config.ResolvedCluster, destFile string) error {
	if err := os.MkdirAll(filepath.Dir(destFile), 0o755); err != nil {
		return err
	}

	roleMap := groupNodesByRole(cluster.Nodes)

	var sb strings.Builder

	sb.WriteString("# Generated by Errant - Ansible Inventory\n\n")

	for role, nodes := range roleMap {
		renderRoleSection(&sb, role, nodes)
	}

	renderChildGroups(&sb, roleMap)

	return os.WriteFile(destFile, []byte(sb.String()), 0o644)
}

func groupNodesByRole(nodes []config.ResolvedNode) map[string][]config.ResolvedNode {
	roleMap := make(map[string][]config.ResolvedNode)

	for _, node := range nodes {
		role := strings.ReplaceAll(node.Role, "-", "_")
		if role == "" {
			role = "ungrouped"
		}

		roleMap[role] = append(roleMap[role], node)
	}

	return roleMap
}

func renderRoleSection(sb *strings.Builder, role string, nodes []config.ResolvedNode) {
	fmt.Fprintf(sb, "[%s]\n", role)

	for _, node := range nodes {
		sb.WriteString(node.Name)

		if node.IP != "" {
			fmt.Fprintf(sb, " ansible_host=%s", node.IP)
		}

		user := node.SSH.User
		if user == "" {
			user = "errant"
		}

		fmt.Fprintf(sb, " ansible_user=%s", user)
		sb.WriteString(" ansible_ssh_common_args='-o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null'\n")
	}

	sb.WriteString("\n")
}

func renderChildGroups(sb *strings.Builder, roleMap map[string][]config.ResolvedNode) {
	var childGroups []string

	if _, ok := roleMap["control_plane"]; ok {
		childGroups = append(childGroups, "control_plane")
	}

	if _, ok := roleMap["worker"]; ok {
		childGroups = append(childGroups, "worker")
	}

	if len(childGroups) > 0 {
		sb.WriteString("[k8s_cluster:children]\n")

		for _, g := range childGroups {
			sb.WriteString(g)
			_ = sb.WriteByte('\n')
		}

		sb.WriteString("\n")
	}
}
